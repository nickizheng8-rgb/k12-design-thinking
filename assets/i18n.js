/* 语言库：应用 / 切换 / 取值 */
(function () {
  "use strict";
  var KEY = "dt_lang";
  function $$ (sel, root) { return Array.prototype.slice.call((root || document).querySelectorAll(sel)); }

  function current() {
    try { return localStorage.getItem(KEY) === "en" ? "en" : "zh"; }
    catch (e) { return "zh"; }
  }

  function t(key, params) {
    var dict = window.I18N[current()] || {};
    var s = dict[key];
    if (typeof s !== "string") s = (window.I18N.zh[key] || key);
    if (params) {
      Object.keys(params).forEach(function (k) {
        s = s.replace("{" + k + "}", params[k]);
      });
    }
    return s;
  }

  function apply(lang) {
    if (!window.I18N[lang]) lang = "zh";
    try { localStorage.setItem(KEY, lang); } catch (e) { }
    document.documentElement.lang = (lang === "en") ? "en" : "zh-CN";

    var page = document.body.getAttribute("data-page") || "index";
    document.title = t("meta.title." + page);
    var md = document.querySelector('meta[name="description"]');
    if (md) md.setAttribute("content", t("meta.desc." + page));

    $$("[data-i18n]").forEach(function (el) {
      var v = t(el.getAttribute("data-i18n"));
      if (el.getAttribute("data-i18n-allow-html") === "true") { el.innerHTML = v; }
      else { el.textContent = v; }
    });
    $$("[data-i18n-placeholder]").forEach(function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    $$("[data-i18n-aria]").forEach(function (el) {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });

    var btn = document.querySelector("[data-lang-toggle]");
    if (btn) {
      btn.textContent = t("app.lang.short");
      btn.setAttribute("aria-label", t("app.lang.switch"));
    }

    document.dispatchEvent(new CustomEvent("langchange", { detail: { lang: lang } }));
  }

  function toggle() {
    apply(current() === "zh" ? "en" : "zh");
  }

  window.I18N_LIB = { current: current, apply: apply, toggle: toggle, t: t };

  /* 首屏立即应用（脚本位于 body 尾部，先于首帧渲染） */
  document.addEventListener("DOMContentLoaded", function () {
    var btn = document.querySelector("[data-lang-toggle]");
    if (btn) btn.addEventListener("click", toggle);
    apply(current());
  });
})();
